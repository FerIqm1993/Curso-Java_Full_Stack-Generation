// Las variables nos sirven para guardar datos
// Existen 3 tipos de variables: const, let y var
// const: es una variable que no se puede cambiar
// let: es una variable que se puede cambiar
// var: es una variable que se puede cambiar

const nombre = "Juan";
let edad = 25;
var altura = 1.75;

console.log(nombre);
console.log(edad);
console.log(altura);

edad = 26;
altura = 1.80;

console.log(edad);
console.log(altura);

// typeof nos sirve para saber el tipo de variable
console.log(typeof nombre);
console.log(typeof edad);
console.log(typeof altura);

